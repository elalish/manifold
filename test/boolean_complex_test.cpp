// Largest distance from points on a grid over every triangle of result to the
// nearer input surface. Degenerate cleanup must keep this within epsilon.
// Measuring triangle interiors matters: moving a vertex onto another one leaves
// every vertex on the inputs while the triangles between them may move.
double MaxDistToInputs(const Manifold& result,
                       const std::vector<MeshGL64>& inputs) {
  auto tri = [](const MeshGL64& m, size_t t) {
    std::array<vec3, 3> v;
    for (int i : {0, 1, 2})
      for (int j : {0, 1, 2})
        v[i][j] = m.vertProperties[m.numProp * m.triVerts[3 * t + i] + j];
    return v;
  };
  const MeshGL64 out = result.GetMeshGL64();
  constexpr int kGrid = 16;
  double maxDist2 = 0;
  for (size_t t = 0; t < out.NumTri(); ++t) {
    const std::array<vec3, 3> v = tri(out, t);
    for (int i = 0; i <= kGrid; ++i) {
      for (int j = 0; i + j <= kGrid; ++j) {
        const vec3 p = (v[0] * double(kGrid - i - j) + v[1] * double(i) +
                        v[2] * double(j)) /
                       double(kGrid);
        double dist2 = std::numeric_limits<double>::infinity();
        for (const MeshGL64& in : inputs)
          for (size_t s = 0; s < in.NumTri(); ++s)
            dist2 = std::min(
                dist2, DistanceTriangleTriangleSquared(tri(in, s), {p, p, p}));
        maxDist2 = std::max(maxDist2, dist2);
      }
    }
  }
  return std::sqrt(maxDist2);
}

